"""Write REPORT.md from results.json plus the hand-written findings.md.

    python benchmarks/social/report.py

Every number in the tables comes from results.json; findings.md holds the
plain-language reading of them and is inserted verbatim.
"""

from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
LABEL = {
    "flat": "float32 (flat)",
    "sq8": "SQ8",
    "pq": "PQ",
    "rabitq4": "RaBitQ 4-bit",
    "rabitq2": "RaBitQ 2-bit",
    "rabitq1": "RaBitQ 1-bit",
}


def codes(m: dict) -> float:
    return m["memory_report"]["vector_bytes"] / m["n"]


def table(ds: dict) -> list[str]:
    modes = ds["modes"]
    out = [
        "| Mode | Search bytes/vector | vs float32 | Disk total/vector "
        "| Disk codes/vector | Recall@10 | No rerank | Peak RSS MiB |",
        "|---|--:|--:|--:|--:|--:|--:|--:|",
    ]
    for k, label in LABEL.items():
        if k not in modes:
            continue
        m, nr = modes[k], modes.get(f"{k}-norerank")
        no_rerank = f"{nr['recall_at_10']:.4f}" if nr else "-"
        out.append(
            f"| {label} | {codes(m):,.0f} | {codes(modes['flat']) / codes(m):.1f}x "
            f"| {m['disk_bytes_per_vector_total']:,.0f} "
            f"| {m['disk_bytes_per_vector_search_codes']:,.0f} "
            f"| {m['recall_at_10']:.4f} | {no_rerank} | {m['peak_rss_mib']:,.0f} |"
        )
    return out


def dataset_section(name: str, ds: dict) -> list[str]:
    p = ds["provenance"]
    m = next(iter(ds["modes"].values()))
    lines = [
        f"### {name}",
        "",
        f"- Source: {p['source']}",
        f"- Licence: {p['licence']}",
        f"- Vectors: {m['n']:,} x {m['dim']}-d, {m['queries']:,} queries, "
        f"k={m['k']}; ground truth: {p['ground_truth']}",
    ]
    if p.get("subset"):
        lines.append(f"- Subset: {p['subset']} (revision `{p['revision']}`)")
    for f in p.get("files", []):
        lines.append(
            f"- File `{f['file']}`: {f['bytes']:,} bytes, sha256 `{f['sha256']}`"
            + (
                " (verified against source)"
                if f["sha256_verified_against_source"]
                else ""
            )
        )
    lines.append(
        f"- Preparation (download + load + ground truth): {ds['prepare_seconds']} s"
    )
    return [*lines, "", *table(ds), ""]


def main() -> None:
    res = json.loads((HERE / "results.json").read_text())
    env = res["environment"]
    out = [
        "# SrvDB memory and recall report",
        "",
        "Generated by `benchmarks/social/report.py` from `results.json`; do not "
        "edit the tables by hand. Speed is not measured (see the last section).",
        "",
        "## Environment",
        "",
        f"- CPU: {env['cpu']} ({env['logical_cpus']} logical CPUs), "
        f"{env['ram_gib']} GiB RAM",
        f"- OS: {env['os']}; Python {env['python']}",
        f"- SrvDB {env['srvdb_version']}, commit `{env['git_commit']}`"
        + (" (tree had uncommitted changes)" if env["git_tree_dirty"] else ""),
        f"- Command: `{env['command']}` (run {env['date_utc']})",
        "",
        "## Method",
        "",
        "Each dataset is prepared in its own process (download, verify, "
        "L2-normalise, ground truth), then each mode is built from scratch in a "
        "separate process with `srvdb.create(path, dim, index=..., **options)`, "
        "fed in batches of 10,000 with default options, saved, and queried with "
        "`search_batch(queries, 10)`. Search bytes/vector is "
        "`db.memory_report()['vector_bytes'] / n`; disk columns divide the files "
        "in the database directory by n (files are preallocated past n, and "
        "RaBitQ keeps float32 vectors for rerank). Peak RSS is `ru_maxrss` of the "
        "mode's process and includes the benchmark's own copy of the vectors. "
        "'No rerank' is RaBitQ after `set_rabitq_rerank(0)`.",
        "",
        (HERE / "findings.md").read_text().rstrip(),
        "",
        "## Results by dataset",
        "",
    ]
    for name, ds in res["datasets"].items():
        out += dataset_section(name, ds)
    crash = res.get("crash_test")
    if crash:
        out += [
            "## Crash test (kill -9)",
            "",
            f"Command: `{crash['command']}`; passed: {crash['passed']}; "
            f"kills: {crash['kills_total']:,}; committed records lost: "
            f"{crash['committed_lost']}.",
            "",
            "| Mode | Kills | Committed vectors verified |",
            "|---|--:|--:|",
            *(
                f"| {k} | {v['kills']:,} | {v['committed_verified']:,} |"
                for k, v in crash["per_mode"].items()
            ),
            "",
        ]
    out += [
        "## Not measured yet",
        "",
        "- QPS, latency and build time: they depend on machine load and wait for "
        "the idle-machine run (#54).",
        "- SIFT-1M (`sift-128-euclidean`): SrvDB is cosine-only; SIFT ground "
        "truth is Euclidean.",
        "- DBpedia 500k / 1M, GIST and larger sets: out of scope for this "
        "laptop's free memory (about 9 GB).",
        "",
    ]
    (HERE / "REPORT.md").write_text("\n".join(out))


if __name__ == "__main__":
    main()
